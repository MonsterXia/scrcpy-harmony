const { test } = require('node:test')
const assert = require('node:assert/strict')
const { execFileSync } = require('node:child_process')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
test('built CLI package runs outside repository with no application or native dependencies', t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'plus-cli-package-')); t.after(() => fs.rmSync(directory, { recursive: true, force: true }))
  execFileSync(process.execPath, ['script/build-cli.mjs', '--out', directory], { stdio: 'pipe' })
  const pkg = JSON.parse(fs.readFileSync(path.join(directory, 'package.json'), 'utf8'))
  assert.equal(pkg.bin['scrcpy-plus'], 'index.cjs')
  assert.equal(pkg.dependencies, undefined)
  const result = execFileSync(process.execPath, [path.join(directory, pkg.bin['scrcpy-plus']), 'schema', '--json'], { cwd: os.tmpdir(), encoding: 'utf8' })
  assert.equal(JSON.parse(result).data.apiVersion, 1)
  assert.ok(fs.readFileSync(path.join(directory, 'LICENSE'), 'utf8').length > 100)
})
