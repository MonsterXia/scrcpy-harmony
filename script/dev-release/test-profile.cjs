const {test}=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs/promises')
const os=require('node:os')
const path=require('node:path')
test('replacement must retain settings and main store bytes including overview choice',async t=>{
  const root=await fs.mkdtemp(path.join(os.tmpdir(),'dev2-profile-'));t.after(()=>fs.rm(root,{recursive:true,force:true}))
  await fs.mkdir(path.join(root,'data'))
  await fs.writeFile(path.join(root,'data/settings.json'),JSON.stringify({language:'en-US',theme:'dark',betaUpdate:true}))
  await fs.writeFile(path.join(root,'data/main.json'),JSON.stringify({panel:'settings',overviewTarget:{key:'harmony:release-fixture'}}))
  const {snapshotProfile,assertProfilePreserved}=await import('./profile-check.mjs')
  const before=await snapshotProfile(root)
  assertProfilePreserved(before,await snapshotProfile(root))
  await fs.writeFile(path.join(root,'data/main.json'),'{}')
  const changed=await snapshotProfile(root)
  assert.throws(()=>assertProfilePreserved(before,changed))
  await fs.unlink(path.join(root,'data/main.json'))
  await assert.rejects(snapshotProfile(root))
})
